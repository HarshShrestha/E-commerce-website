import userModel from '../models/user.model.js'
import validator from 'validator';
import bcrypt from "bcrypt";
import jwt from 'jsonwebtoken';

//creating token for user
const createToken = (id)=>{
    return jwt.sign({id},process.env.JWT_SECRET)
}

// Route for user Login
const loginUser = async(req,res)=>{
    try {
        const {email,password} = req.body;
        const user = await userModel.findOne({email});
        if(!user){
            return res.json({success:false,message:"User doesn't exists"})
        }

        const isMatch = await bcrypt.compare(password,user.password);
        if(isMatch){ //password matches
            const token = createToken(user._id);
            res.json({success:true,token});
        }else{  //password didnt match
            res.json({success:false,msg:"invalid credentials"});
        }
        return res.json({success:true,msg:"login route"})
    } catch (error) {
        console.log(error);
        res.json({success:false,msg: error.message})
    }
}

// Route for user registration / sign up
const registerUser = async(req,res)=>{
    try{
        const {name,email,password} = req.body;
        //checking if user already exists or not
        const exists = await userModel.findOne({email});
        if(exists){
            return res.json({success:false , msg : "user already exists"})
        }

        //Credential validator : else check if user email and password is valid
        //email 
        if(!validator.isEmail(email)){
            return res.json({success:false , msg : "please enter a valid email"})
        }
        //password 
        if(password.length < 8){
            return res.json({success:false , msg : "please enter a strong password"})
        }

        //form the user credentials but...
        // 1st : hash the userpassword and store it => using bcrypt package

        //hashing user-password
        const salt = await bcrypt.genSalt(10)
        const hashedPassword = await bcrypt.hash(password,salt) // final hashed pasword

        //final => create user
        const newUser  = new userModel({name,email,password: hashedPassword})
        const user = await newUser.save(); //user stored in the databse

        //create token
        const token = createToken(user._id) //_id auto generated by mongodb
        res.json({success:true, token})


    }catch(error){
        console.log(error);
        res.json({success:false,msg: error.message})
    }
}

// Route for admin login
const adminLogin = async(req,res)=>{
    try {
        const {email,password} = req.body;
        if(email===process.env.ADMIN_EMAIL && password===process.env.ADMIN_PASSWORD){
            //access granted => assign a token
            //generate the token
            const token = jwt.sign(email+password , process.env.JWT_SECRET );
            //now send this token to admin user
            res.json({success:true,token});
            //then authenticate using this token via a middleware
        }else{
            res.json({success:false,msg:"invalid credentials"});
        }
    } catch (error) {
        console.log(error);
        res.json({success:false,msg: error.message})
    }
}

export {loginUser,registerUser,adminLogin}